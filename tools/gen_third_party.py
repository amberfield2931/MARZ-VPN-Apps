#!/usr/bin/env python3
"""Builds THIRD-PARTY-NOTICES.txt from what the builds really use: Cargo.lock with the local crate cache, and
`go list -deps` of sing-box for Linux and Windows. Prints what it could not find; it never guesses a license.
Usage: gen_third_party.py <sing-box source> <wintun LICENSE.txt> > THIRD-PARTY-NOTICES.txt"""
import glob, hashlib, os, re, subprocess, sys
CARGO = os.environ['CARGO_HOME']; GOPATH = os.environ['GOPATH']
src, wintun = sys.argv[1], sys.argv[2]
NAMES = re.compile(r'^(licen[cs]e|copying|notice|unlicense)', re.I)

def texts(d):
    out = []
    for n in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        p = os.path.join(d, n)
        if os.path.isfile(p) and NAMES.match(n):
            out.append((n, open(p, errors='replace').read().strip()))
    return out

missing, rust, go = [], [], []
lock = open('Cargo.lock').read()
for name, ver, rest in re.findall(r'\[\[package\]\]\nname = "([^"]+)"\nversion = "([^"]+)"\n(.*?)(?=\n\[\[package\]\]|\Z)', lock, re.S):
    if 'registry+' not in rest:
        continue
    dirs = glob.glob(f'{CARGO}/registry/src/*/{name}-{ver}')
    if not dirs:
        continue  # never built on Linux or Windows x64 here: no cached source means it is not compiled in
    toml = open(os.path.join(dirs[0], 'Cargo.toml'), errors='replace').read()
    m = re.search(r'^license\s*=\s*"([^"]+)"', toml, re.M)
    t = texts(dirs[0])
    if not m and not t:
        missing.append(f'{name} {ver}')
    rust.append((name, ver, m.group(1) if m else 'see text', t))
env = dict(os.environ, CGO_ENABLED='0')
mods = set()
for goos in ('linux', 'windows'):
    q = subprocess.run(['go', 'list', '-deps', '-tags', 'with_gvisor,with_utls,with_clash_api', '-f', '{{if not .Standard}}{{with .Module}}{{.Path}}@{{.Version}}{{end}}{{end}}', './cmd/sing-box'],
                       cwd=src, env=dict(env, GOOS=goos, GOARCH='amd64'), capture_output=True, text=True, check=True).stdout
    mods |= {x for x in q.split() if '@' in x and not x.endswith('@')}
for mod in sorted(mods):
    path, ver = mod.split('@')
    enc = re.sub(r'[A-Z]', lambda m: '!' + m.group().lower(), path)
    d = f'{GOPATH}/pkg/mod/{enc}@{ver}'
    t = texts(d)
    if not t:
        missing.append(mod)
    go.append((path, ver, t))

print('MARZ VPN Desktop: third-party notices\n')
print('Generated by tools/gen_third_party.py from the build inputs. MARZ VPN Desktop itself is GPL-3.0-or-later (LICENSE).\n')
print('=' * 72 + '\nsing-box 1.14.3 (engine, separate executable). Linux: unmodified. Windows: installed as marzvpn-engine.exe, with the loading of wintun.dll changed (see the corresponding source)\n' + '=' * 72)
print(open(os.path.join(src, 'LICENSE')).read().strip())
print('\n' + '=' * 72 + '\nWintun 0.14.1 (Windows only). The official signed wintun.dll, unmodified, is installed next to the program and used only through the API of wintun.h.\nCopyright WireGuard LLC.\n' + '=' * 72)
print(open(wintun).read().strip())
def block(title, path):
    print('\n' + '=' * 72 + '\n' + title + '\n' + '=' * 72)
    print(open(path, errors='replace').read().strip())
HERE = os.path.dirname(os.path.abspath(__file__))
block('WinDivert 2.2.2 driver (Windows only). Unmodified WinDivert64.sys embedded in the engine by sing-box, used under the LGPL-3.0 option. Copyright basil00. Source: included in the corresponding source and at https://github.com/basil00/WinDivert/tree/v2.2.2. MARZ VPN does not use this feature', f'{HERE}/licenses/WinDivert-LICENSE.txt')
block('Microsoft WebView2Loader.dll (Windows only). License text of the Microsoft.Web.WebView2 package', f'{HERE}/licenses/WebView2-LICENSE.txt')
block('Roboto font (app/ui/fonts)', f'{HERE}/../app/ui/fonts/LICENSE')
sysroot = subprocess.run(['rustc', '--print', 'sysroot'], capture_output=True, text=True, check=True).stdout.strip()
print('\n' + '=' * 72 + '\nRust standard library, statically linked into the app and the helper. MIT OR Apache-2.0; (c) The Rust Project Contributors\nhttps://www.rust-lang.org/policies/licenses\n' + '=' * 72)
for name in ('LICENSE-MIT', 'LICENSE-APACHE'):
    for f in glob.glob(f'{sysroot}/share/doc/rust/licenses/*{name}*')[:1]:
        print(open(f, errors='replace').read().strip())
goroot = subprocess.run(['go', 'env', 'GOROOT'], capture_output=True, text=True, check=True).stdout.strip()
block('Go standard library and runtime, statically linked into sing-box', f'{goroot}/LICENSE')
mingw = '/mnt/marz-lab/toolchains/desktop/mingw/root/usr/share/doc'
block('mingw-w64 runtime and GCC runtime parts, statically linked into the Windows app and helper', f'{mingw}/mingw-w64-common/copyright')
block('NSIS installer stub and plugins (Windows installer only)', f'{mingw}/nsis-common/copyright')
seen = {}
def emit(title, ts):
    print('\n--- ' + title)
    for n, x in ts:
        h = hashlib.sha256(x.encode()).hexdigest()
        if h in seen:
            print(f'{n}: same text as {seen[h]}')
        else:
            seen[h] = title
            print(f'{n}:\n{x}')
print('\n' + '=' * 72 + '\nGo modules compiled into sing-box\n' + '=' * 72)
for path, ver, t in go:
    emit(f'{path} {ver}', t)
print('\n' + '=' * 72 + '\nRust crates compiled into the app and the helper\n' + '=' * 72)
for name, ver, lic, t in rust:
    emit(f'{name} {ver} ({lic})', t)
print(f'NOTICE COUNTS rust={len(rust)} go={len(go)} missing={missing}', file=sys.stderr)
